export function getPdfT(locale: PdfLocale, key: string): string {
  return pdfTranslations[locale]?.[key] ?? pdfTranslations["en"][key] ?? key;
}

export function formatDateForPdf(date: Date, locale: PdfLocale): string {
  try {
    const loc = locale === "ar" ? "ar-EG" : locale === "fr" ? "fr-FR" : "en-GB";
    return new Date(date).toLocaleString(loc, {
      day: "2-digit",
      month: "long",
      year: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return new Date(date).toLocaleString("en-GB");
  }
}
